import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(resolve(root, "web/package.json"));
const YAML = require("yaml");
const openAPIPath = resolve(root, "contracts/openapi.yaml");
const outputRoot = resolve(root, "contracts/generated");
const check = process.argv.includes("--check");

function generatedHeader() {
  return "// Code generated by scripts/generate-developer-artifacts.mjs from contracts/openapi.yaml. DO NOT EDIT.\n// Provenance digest: contracts/generated/sdk-manifest.json.\n\n";
}

function normalizeOperations(document) {
  const methods = new Set(["get", "post", "put", "patch", "delete"]);
  return Object.entries(document.paths ?? {})
    .filter(([, item]) => item?.["x-internal"] !== true)
    .flatMap(([path, item]) => Object.entries(item)
    .filter(([method, operation]) => methods.has(method) && operation?.operationId && operation["x-internal"] !== true)
    .map(([method, operation]) => ({
      id: operation.operationId,
      method: method.toUpperCase(),
      path,
      scope: operation["x-required-scope"] ?? "",
      idempotent: (operation.parameters ?? []).some((parameter) => parameter?.$ref === "#/components/parameters/IdempotencyKey"),
    })))
    .sort((left, right) => left.id.localeCompare(right.id));
}

function typeScriptClient(version, sourceHash, operations) {
  const catalogue = JSON.stringify(operations, null, 2);
  return `${generatedHeader()}export const apiVersion = ${JSON.stringify(version)} as const;

export type Operation = { id: string; method: string; path: string; scope: string; idempotent: boolean };
export const operations: readonly Operation[] = ${catalogue} as const;

export type ClientOptions = { baseUrl: string; fetch?: typeof globalThis.fetch; token: string; actorAssertion: string };

export function createClient(options: ClientOptions) {
  const request = options.fetch ?? globalThis.fetch;
  return {
    operations,
    async call(operation: Operation, path: string, init: RequestInit = {}) {
      const response = await request(new URL(path, options.baseUrl), {
        ...init,
        method: operation.method,
        headers: { Authorization: \`Bearer \${options.token}\`, "X-LedgerSync-Actor-Assertion": options.actorAssertion, ...init.headers },
      });
      return response;
    },
  };
}
`;
}

function goClient(version, sourceHash, operations) {
  const entries = operations.map(({ id, method, path, scope, idempotent }) => `\t{ID: ${JSON.stringify(id)}, Method: ${JSON.stringify(method)}, Path: ${JSON.stringify(path)}, Scope: ${JSON.stringify(scope)}, Idempotent: ${idempotent}},`).join("\n");
  return `${generatedHeader()}package ledgersync

const APIVersion = ${JSON.stringify(version)}

type Operation struct {
	ID, Method, Path, Scope string
	Idempotent              bool
}

var Operations = []Operation{
${entries}
}
`;
}

function postmanCollection(version, sourceHash, operations) {
  return `${JSON.stringify({
    info: { name: "LedgerSync Private API", schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json", version, _postman_id: `ledgersync-${sourceHash.slice(0, 8)}-${sourceHash.slice(8, 16)}-${sourceHash.slice(16, 24)}` },
    variable: [{ key: "baseUrl", value: "http://127.0.0.1:3000/api" }, { key: "bearerToken", value: "REPLACE_WITH_PROTECTED_TOKEN" }, { key: "actorAssertion", value: "REPLACE_WITH_SERVER_ASSERTION" }],
    item: operations.map((operation) => ({ name: operation.id, request: { method: operation.method, header: [{ key: "Authorization", value: "Bearer {{bearerToken}}" }, { key: "X-LedgerSync-Actor-Assertion", value: "{{actorAssertion}}" }].concat(operation.idempotent ? [{ key: "Idempotency-Key", value: `example-${operation.id}-key` }] : []), url: "{{baseUrl}}" + operation.path } })),
  }, null, 2)}\n`;
}

async function materialize(path, content) {
  if (check) {
    try { if (await readFile(path, "utf8") === content) return; }
    catch { /* report the deliberate generated-artifact drift below */ }
    throw new Error(`generated artifact drift: ${path.replace(root + "\\", "")}. Run npm --prefix web run generate:developer-artifacts.`);
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

// Git may materialize the reviewed YAML with CRLF on Windows. Normalize before
// parsing and hashing so generated artifacts are identical in local and Linux CI.
const source = (await readFile(openAPIPath, "utf8")).replace(/\r\n/g, "\n");
const document = YAML.parse(source);
const version = document?.info?.version;
if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error("OpenAPI info.version must be semantic versioning");
const operations = normalizeOperations(document);
if (operations.length === 0 || operations.some((operation) => !operation.scope)) throw new Error("every generated operation must declare x-required-scope");
const sourceHash = createHash("sha256").update(source).digest("hex");
const sourceHashChunks = sourceHash.match(/.{1,8}/g);

await Promise.all([
  materialize(resolve(outputRoot, "sdk-manifest.json"), JSON.stringify({ schema_version: 1, api_version: version, source: "contracts/openapi.yaml", openapi_sha256_chunks: sourceHashChunks, operations }, null, 2) + "\n"),
  materialize(resolve(outputRoot, "typescript/ledgersync.ts"), typeScriptClient(version, sourceHash, operations)),
  materialize(resolve(outputRoot, "go/ledgersync.go"), goClient(version, sourceHash, operations)),
  materialize(resolve(outputRoot, "ledgersync.postman_collection.json"), postmanCollection(version, sourceHash, operations)),
]);
