import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const reports = ["api-failure.json", "parallel-workers.json", "causal-trace.json", "concurrent-transfers.json", "snapshot-report.json", "scheduler-takeover.json", "performance/comparison.json", "recovery-report.json"];
let text = "# LedgerSync: historical study evidence\n\nThese are recorded tests with synthetic data. They are not current service health. Delivery is at least once. PostgreSQL remains the financial authority.\n\n";
for (const file of reports) {
  const report = JSON.parse(await readFile(resolve(root, "docs/release-evidence/unit-3-unit-4", file), "utf8"));
  const serialized = JSON.stringify(report, null, 2);
  if (/bearer\s+[A-Za-z0-9]|postgres:\/\/|password"\s*:|csrf_token"\s*:|assertion"\s*:/i.test(serialized)) throw new Error(`Unsafe evidence in ${file}`);
  text += `## ${file}\n\nSource: docs/release-evidence/unit-3-unit-4/${file}\n\n\`\`\`json\n${serialized}\n\`\`\`\n\n`;
}
const target = resolve(root, "web/src/lib/generated/unit-study-evidence.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(target, `// Generated by scripts/generate-unit-study-evidence.mjs. Historical synthetic evidence only.\nexport const unitStudyEvidence = ${JSON.stringify(text)};\n`);
